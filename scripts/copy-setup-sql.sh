#!/usr/bin/env bash
# Builds the full database setup (migrations in order + demo seed) as one SQL script and copies it
# to the Windows clipboard (WSL), ready to paste into the Supabase SQL Editor.
# Usage: scripts/copy-setup-sql.sh [--no-seed] [--print]
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$(mktemp --suffix=.sql)"
SEED=1; PRINT=0
for arg in "$@"; do
  case "$arg" in
    --no-seed) SEED=0 ;;
    --print) PRINT=1 ;;
  esac
done

{
  echo "-- Full database setup, generated by scripts/copy-setup-sql.sh on $(date -I)"
  for f in "$ROOT"/supabase/migrations/*.sql; do
    printf '\n-- >>> %s\n' "$(basename "$f")"
    cat "$f"
  done
  if [ "$SEED" = 1 ]; then
    printf '\n-- >>> seed.sql (demo data)\n'
    cat "$ROOT/supabase/seed.sql"
  fi
} > "$OUT"

if [ "$PRINT" = 1 ]; then
  cat "$OUT"
elif command -v powershell.exe >/dev/null; then
  # PowerShell keeps UTF-8 characters intact (clip.exe would garble them).
  powershell.exe -NoProfile -Command "Set-Clipboard -Value (Get-Content -Raw -Encoding UTF8 -LiteralPath '$(wslpath -w "$OUT")')"
  echo "Copied $(wc -l < "$OUT") lines to the clipboard. Paste them into Supabase > SQL Editor > New query, then Run."
else
  echo "No clipboard tool found. Run with --print and copy the output." >&2
  exit 1
fi
rm -f "$OUT"
