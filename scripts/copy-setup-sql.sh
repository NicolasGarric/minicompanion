#!/usr/bin/env bash
# Builds the full database setup (migrations in order + demo seed) as ONE re-runnable SQL script and
# copies it to the Windows clipboard (WSL), ready to paste into the Supabase SQL Editor.
#
# Each file is wrapped in a DO block that runs only if its marker object does not exist yet, so the
# script can be pasted again after a partial run without "already exists" errors.
# Usage: scripts/copy-setup-sql.sh [--no-seed] [--print] [--from N] [--status]
#   --from N   only migrations number N and later (the last digits of the file name, e.g. 16)
#   --status   instead of the setup, a read-only query listing each migration as applied / to apply
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SEED=1; PRINT=0; FROM=0; STATUS=0
while [ $# -gt 0 ]; do
  case "$1" in
    --no-seed) SEED=0 ;;
    --print) PRINT=1 ;;
    --from) FROM="$2"; shift ;;
    --status) STATUS=1; SEED=0 ;;
  esac
  shift
done

# file -> SQL condition that is true when the file still has to run
declare -A GUARD=(
  [20261021000001_core.sql]="to_regclass('public.profiles') is null"
  [20261021000002_play.sql]="to_regclass('public.tournaments') is null"
  # Idempotent fixes: always run.
  [20261022000003_fix_tournament_select_policy.sql]="true"
  [20261023000004_gallery.sql]="to_regclass('public.gallery_items') is null"
  [20261024000005_quick_play.sql]="to_regclass('public.games') is null"
  [20261025000006_play_social.sql]="to_regclass('public.game_reports') is null"
  [20261026000007_owner_decisions.sql]="to_regprocedure('public.purge_check_games()') is null"
  [20261027000008_tournament_flow.sql]="to_regprocedure('public.create_round(uuid,jsonb)') is null"
  [20261028000009_painting_contest.sql]="to_regprocedure('public.cast_contest_vote(uuid)') is null"
  [20261029000010_languages.sql]="not exists (select 1 from pg_enum e join pg_type t on t.oid = e.enumtypid where t.typname = 'app_lang' and e.enumlabel = 'ko')"
  [20261030000011_round_schedule.sql]="to_regclass('public.round_schedule') is null"
  [20261031000012_bug_reports.sql]="to_regclass('public.bug_reports') is null"
  [20261101000013_security_hardening.sql]="to_regprocedure('public.my_profile()') is null"
  # (no error when the table or the column is not there yet)
  [20261102000014_organiser_archive.sql]="not coalesce((select has_column_privilege('authenticated', a.attrelid, a.attnum, 'UPDATE') from pg_attribute a where a.attrelid = to_regclass('public.tournaments') and a.attname = 'is_hidden' and not a.attisdropped), false)"
  [20261103000015_hobby_community.sql]="to_regclass('public.season_challenges') is null"
  [20261104000016_admin_dashboard.sql]="to_regclass('public.page_views_daily') is null"
  [20261105000017_photo_storage.sql]="to_regprocedure('public.my_photo_usage()') is null"
  [20261106000018_translation_suggestions.sql]="to_regclass('public.translation_suggestions') is null"
  [20261107000019_security_fixes.sql]="to_regproc('public.thumb_has_main') is null"
  [20261108000020_game_maps.sql]="to_regproc('public.set_game_map') is null"
  [20261109000021_narrative_campaigns.sql]="to_regclass('public.campaigns') is null"
  [20261110000022_delete_game.sql]="to_regproc('public.delete_game') is null"
)
seq_of() { local n="${1%%_*}"; echo $((10#${n: -6})); } # 20261104000016_x.sql -> 16

wrap() { # $1 = file, $2 = condition, $3 = label
  local tag="setup_$(basename "$1" .sql | tr -c "a-z0-9_\n" "_")"
  if grep -q "\$$tag\\$" "$1"; then echo "dollar tag clash in $1" >&2; exit 1; fi
  printf '\n-- >>> %s (skipped automatically if already applied)\n' "$3"
  printf 'do $guard$ begin\n  if %s then\n    execute $%s$\n' "$2" "$tag"
  cat "$1"
  printf '\n$%s$;\n    raise notice %s;\n  else\n    raise notice %s;\n  end if;\nend $guard$;\n' \
    "$tag" "'applied: $3'" "'already there, skipped: $3'"
}

OUT="$(mktemp --suffix=.sql)"
if [ "$STATUS" = 1 ]; then
  {
    echo "-- Which migrations are in this database (read-only). Generated by scripts/copy-setup-sql.sh --status."
    sep="select"
    for f in "$ROOT"/supabase/migrations/*.sql; do
      name="$(basename "$f")"
      cond="${GUARD[$name]:-}"
      if [ -z "$cond" ]; then echo "No guard defined for $name in $0" >&2; exit 1; fi
      if [ "$cond" = "true" ]; then state="'always safe to run'"; else state="case when $cond then 'TO APPLY' else 'applied' end"; fi
      printf "%s %d as n, '%s' as migration, %s as state\n" "$sep" "$(seq_of "$name")" "$name" "$state"
      sep="union all select"
    done
    echo "order by n;"
  } > "$OUT"
else
{
  echo "-- Database setup, generated by scripts/copy-setup-sql.sh on $(date -I). Safe to run again."
  for f in "$ROOT"/supabase/migrations/*.sql; do
    name="$(basename "$f")"
    cond="${GUARD[$name]:-}"
    if [ -z "$cond" ]; then echo "No guard defined for $name in $0" >&2; exit 1; fi
    [ "$(seq_of "$name")" -ge "$FROM" ] || continue
    wrap "$f" "$cond" "$name"
  done
  if [ "$SEED" = 1 ]; then
    wrap "$ROOT/supabase/seed.sql" "not exists (select 1 from public.stores)" "seed.sql (demo data)"
    wrap "$ROOT/supabase/seed_games.sql" "not exists (select 1 from public.games) and exists (select 1 from public.stores)" "seed_games.sql (demo quick play games)"
    wrap "$ROOT/supabase/seed_social.sql" "not exists (select 1 from public.leagues) and exists (select 1 from public.stores)" "seed_social.sql (demo reports, league, posts)"
    wrap "$ROOT/supabase/seed_contest.sql" "not exists (select 1 from public.tournaments where slug = 'summer-paint-off') and exists (select 1 from public.stores)" "seed_contest.sql (demo painting contests)"
    wrap "$ROOT/supabase/seed_tournament.sql" "not exists (select 1 from public.tournaments where slug = 'kanda-live-friday') and exists (select 1 from public.stores)" "seed_tournament.sql (demo tournament in progress)"
  fi
} > "$OUT"
fi

if [ "$PRINT" = 1 ]; then
  cat "$OUT"
elif command -v powershell.exe >/dev/null; then
  # PowerShell keeps UTF-8 characters intact (clip.exe would garble them).
  powershell.exe -NoProfile -Command "Set-Clipboard -Value (Get-Content -Raw -Encoding UTF8 -LiteralPath '$(wslpath -w "$OUT")')"
  echo "Copied $(wc -l < "$OUT") lines to the clipboard. Paste them into Supabase > SQL Editor > New query, then Run."
else
  echo "No clipboard tool found. Run with --print and copy the output." >&2
  exit 1
fi
rm -f "$OUT"
