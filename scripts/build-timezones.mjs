#!/usr/bin/env node
// Builds src/core/data/timezones.ts from the system's tz database (public domain): for each time zone the
// browser can report, its country and main city's coordinates. Only used to open maps in the right part of
// the world and to preselect a country, without asking for the visitor's position or calling any service.
// Usage: node scripts/build-timezones.mjs   (needs /usr/share/zoneinfo)
import { readFileSync, writeFileSync } from 'node:fs';

const DIR = '/usr/share/zoneinfo';
const zones = new Map(); // name -> "CC,lat,lng"
const coord = (s) => {
  // ±DDMM[SS] or ±DDDMM[SS]
  const m = s.match(/^([+-])(\d{2,3})(\d{2})(\d{2})?$/);
  return (m[1] === '-' ? -1 : 1) * (Number(m[2]) + Number(m[3]) / 60);
};
for (const line of readFileSync(`${DIR}/zone.tab`, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [cc, pos, name] = line.split('\t');
  const [, lat, lng] = pos.match(/^([+-]\d{4}(?:\d{2})?)([+-]\d{5}(?:\d{2})?)$/);
  zones.set(name, `${cc},${coord(lat).toFixed(2)},${coord(lng).toFixed(2)}`);
}
// Older names (some browsers still report them, e.g. Asia/Calcutta)
for (const line of readFileSync(`${DIR}/tzdata.zi`, 'utf8').split('\n')) {
  const [kind, target, alias] = line.split(' ');
  if (kind === 'L' && zones.has(target) && alias.includes('/') && !zones.has(alias)) zones.set(alias, zones.get(target));
}
const rows = [...zones].sort(([a], [b]) => (a < b ? -1 : 1)).map(([n, v]) => `${n},${v}`);
writeFileSync(
  new URL('../src/core/data/timezones.ts', import.meta.url),
  `/** GENERATED by scripts/build-timezones.mjs from the tz database (public domain): "zone,country,lat,lng". */\nexport const TIMEZONES =\n  '${rows.join(';')}';\n`,
);
console.log(`${rows.length} time zones`);
