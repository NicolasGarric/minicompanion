// Copies the Google Fonts used by the app into public/fonts/ so that visitors never contact Google
// (their IP address would be sent to Google on every visit: not allowed without consent in the EU).
// Run once, and again only when the font list in FAMILIES changes: node scripts/fetch-fonts.mjs
// The fonts are under the SIL Open Font License (OFL.txt is written next to them).
import { createHash } from 'node:crypto';
import { mkdir, readdir, stat, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'public', 'fonts');
const FAMILIES =
  'family=Noto+Sans+JP:wght@400;500;700&family=Noto+Sans+SC:wght@400;700;900&family=Noto+Sans+KR:wght@400;700;900' +
  '&family=Dela+Gothic+One&family=Zen+Maru+Gothic:wght@500;700&display=swap';
// A current browser: Google then serves woff2 files split by unicode-range (only the needed slices are downloaded).
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/131.0 Safari/537.36';

// Slow links time out now and then: a few tries before giving up.
async function get(url) {
  for (let i = 1; ; i++) {
    try {
      const r = await fetch(url, { headers: { 'User-Agent': UA } });
      if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
      return Buffer.from(await r.arrayBuffer());
    } catch (e) {
      if (i >= 8) throw e;
      await new Promise((ok) => setTimeout(ok, 1000 * i));
    }
  }
}

let css = (await get(`https://fonts.googleapis.com/css2?${FAMILIES}`)).toString('utf8');

// Files already downloaded by an interrupted run are kept (same URL, same name); fonts.css is rewritten.
await mkdir(OUT, { recursive: true });
const have = new Set(await readdir(OUT));

const urls = [...new Set([...css.matchAll(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/g)].map((m) => m[1]))];
let bytes = 0;
const queue = [...urls];
const worker = async () => {
  for (let url = queue.shift(); url; url = queue.shift()) {
    const name = `${createHash('sha1').update(url).digest('hex').slice(0, 16)}.woff2`;
    if (!have.has(name)) {
      const buf = await get(url);
      await writeFile(join(OUT, name), buf);
    }
    bytes += (await stat(join(OUT, name))).size;
    css = css.split(url).join(`/fonts/${name}`);
  }
};
await Promise.all(Array.from({ length: 4 }, worker));

await writeFile(join(OUT, 'fonts.css'), `/* Generated by scripts/fetch-fonts.mjs from Google Fonts (SIL Open Font License). Do not edit. */\n${css}`);
await writeFile(
  join(OUT, 'OFL.txt'),
  'Noto Sans JP, Noto Sans SC, Noto Sans KR, Dela Gothic One and Zen Maru Gothic are licensed under the SIL Open Font License, Version 1.1.\n' +
    'Full text: https://openfontlicense.org/open-font-license-official-text/\n',
);
console.log(`${urls.length} font files, ${(bytes / 1024 / 1024).toFixed(1)} MB, written to public/fonts/`);
